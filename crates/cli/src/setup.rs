const CORE_TS: &str = include_str!("../../../integrations/opencode/core.ts");
const PLUGIN_TS: &str = include_str!("../../../integrations/opencode/saispace.ts");
const MARKER: &str = "// Generated by `sai setup opencode`; reinstall with it, do not edit.";
/// Module folder outside `plugins/`, so `OpenCode` never loads `core.ts`
/// (which has no default export) as a plugin of its own.
const MODULE_DIR: &str = "saispace-plugin";

const CLAUDE_HOOKS: &[(&str, &str)] = &[
    ("SessionStart", "sai memory context 2>/dev/null || true"),
    ("UserPromptSubmit", "sai memory nudge 2>/dev/null || true"),
    ("Stop", "sai memory nudge 2>/dev/null || true"),
    // A lesson whose trigger matches a tool's error comes back right away.
    ("PostToolUse", "sai memory nudge 2>/dev/null || true"),
    ("PostToolUseFailure", "sai memory nudge 2>/dev/null || true"),
];

